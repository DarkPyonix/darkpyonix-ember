/// The numeric id of a proxy identifier by name (`"ExtHostDocuments"` → 95 at the pinned commit).
pub fn id_of(name: &str) -> Option<u8> {
    PROXY_IDS.iter().position(|n| *n == name).map(|i| (i + 1) as u8)
}

/// The name of a numeric id.
pub fn name_of(id: u8) -> Option<&'static str> {
    (id as usize).checked_sub(1).and_then(|i| PROXY_IDS.get(i)).copied()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ids_fit_in_a_byte_and_are_unique() {
        assert!(PROXY_IDS.len() <= 255);
        let mut seen = std::collections::HashSet::new();
        for n in PROXY_IDS {
            assert!(seen.insert(*n), "duplicate {n}");
        }
    }

    /// Spot checks computed by hand from extHost.protocol.ts at the pinned commit.
    #[test]
    fn pinned_ids() {
        assert_eq!(id_of("MainThreadAuthentication"), Some(1));
        assert_eq!(id_of("MainThreadCommands"), Some(10));
        assert_eq!(id_of("MainThreadConfiguration"), Some(12));
        assert_eq!(id_of("MainThreadDiagnostics"), Some(16));
        assert_eq!(id_of("MainThreadDocuments"), Some(18));
        assert_eq!(id_of("MainThreadLanguageFeatures"), Some(26));
        assert_eq!(id_of("MainThreadStorage"), Some(38));
        assert_eq!(id_of("MainThreadExtensionService"), Some(54));
        assert_eq!(id_of("MainThreadBrowsers"), Some(87));
        assert_eq!(id_of("ExtHostCommands"), Some(89));
        assert_eq!(id_of("ExtHostConfiguration"), Some(90));
        assert_eq!(id_of("ExtHostDocumentsAndEditors"), Some(94));
        assert_eq!(id_of("ExtHostDocuments"), Some(95));
        assert_eq!(id_of("ExtHostLanguageFeatures"), Some(104));
        assert_eq!(id_of("ExtHostExtensionService"), Some(110));
        assert_eq!(id_of("ExtHostWorkspace"), Some(117));
        assert_eq!(id_of("ExtHostBrowsers"), Some(168));
        assert_eq!(name_of(0), None);
        assert_eq!(name_of(95), Some("ExtHostDocuments"));
    }
}
