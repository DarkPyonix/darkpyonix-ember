//! Extension-host RPC proxy identifiers.
//!
//! On the wire an RPC request names its target actor by a **one-byte number**, not by name
//! (`rpcProtocol.ts` `_requestJSONArgs`: `result.writeUInt8(rpcId)`). The number is
//! `ProxyIdentifier.nid`, assigned by a global counter in **declaration order** of the
//! `createProxyIdentifier(...)` calls (`proxyIdentifier.ts` L42: `this.nid = (++ProxyIdentifier.count)`).
//! At the pinned commit those calls exist only in `extHost.protocol.ts` (`MainContext` L4046-4134,
//! then `ExtHostContext` L4136-4218), so the numbering is fully determined by that file — and
//! **any insertion upstream shifts every later id**. This is the single most fragile fact in the
//! whole connection; see `docs/design/EDITOR-CONNECTION.md` §5.
//!
//! The table below is generated by `crates/editor-conn/scripts/gen_rpc_ids.sh` from Code-OSS
//! [`crate::PINNED_VERSION`] (commit [`PINNED_COMMIT`], the tag in `build/ose/VERSION`). CI regenerates
//! it at that tag and fails on any difference. Regenerate it for every Code-OSS bump; at runtime
//! [`crate::handshake::verify_server`] refuses servers whose `GET /version` is another commit.

